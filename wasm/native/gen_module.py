"""Generate _dv_native.cc (one submodule per binding) and the submodule -> import path table."""
import json, pathlib, re, sys
root, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
files = [l.strip() for l in open(sys.argv[3]) if l.strip()]
mods = []
for f in files:
    m = re.search(r'PYBIND11_MODULE\(\s*(\w+)', (root / f).read_text())
    if not m: continue
    pkg = str(pathlib.Path(f).parent).replace('/', '.')
    mods.append({'name': m.group(1), 'file': f, 'import_path': f'{pkg}.{m.group(1)}'})
names = [m['name'] for m in mods]
dups = {n for n in names if names.count(n) > 1}
assert not dups, f'duplicate binding names: {dups}'
cc = ['// Generated by gen_module.py: every DeepVariant/Nucleus binding as a submodule of _dv_native.',
      '#include <pybind11/pybind11.h>']
cc += [f'void dv_pybind_init_{m["name"]}(::pybind11::module_& m);' for m in mods]
cc += ['PYBIND11_MODULE(_dv_native, m) {']
cc += [f'  {{ auto sub = m.def_submodule("{m["name"]}"); dv_pybind_init_{m["name"]}(sub); }}' for m in mods]
cc += ['}']
(out / '_dv_native.cc').write_text('\n'.join(cc) + '\n')
(out / 'submodules.json').write_text(json.dumps({m['name']: m['import_path'] for m in mods}, indent=1))
print(f'{len(mods)} bindings:', ' '.join(names))
